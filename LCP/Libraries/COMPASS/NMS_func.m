           Delta, d_count, memory, in_pivot, ...
           pathsearch_type, search_type_change, take_pg_step, mark_check, ...
           checkpointxN, checkpointzN, stop, restart] = ...
         NMS_func( ...
           n, l, u, f, Df, zwvt, infty, ...
           d_count, take_pg_step, ...
           a_k, v_k, w_k, z_k, z_b, ...
           z_k_N, x_k_N, v_k_N, w_k_N, ...
           Delta, Delta0, next_x_near, x_next, memory, Ref, in_pivot, ...
           max_d_count, sigma_NMS, pg_search_type, max_m_alpha_pg, ...
           max_m_alpha_w, major, ...
           mark_check, bestpoint, checkpointx, checkpointz, ...
           checkpointxN, checkpointzN, search_type_change, ...
           pathsearch_type, display_depth, stop, restart, deltachange)
%
